#!/usr/bin/env python3
"""Generates the portable host's engine-interface base classes (headless/portable/host/gen/*).

Reuses the civhost parser (headless/tools/civsim/enginehost/gen_stubs.py) and its classification
(headless/host/api/engine-api.csv), but every body is safe instead of aborting:
  sink   no-op, zero value
  query  the CSV constant
  sim    logged once as unimplemented (lekmod_portable::LogStubOnce), zero value
  gen    ICvUnknown QueryInterface / Destroy
Hand-written subclasses in headless/portable/host override what the portable gamecore needs.

Usage: python3 headless/tools/clang/gen_portable_engine.py   (output is committed)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'headless', 'tools'))

from civsim.enginehost import gen_stubs as g  # noqa: E402

HDR = ('// GENERATED by headless/tools/clang/gen_portable_engine.py from the SDK interface headers and\n'
       '// headless/host/api/engine-api.csv. Do not edit; rerun the script.\n')


def body(m, family, cls, value):
	r = m.ret
	zero = '' if r == 'void' else '\treturn lekmod_portable::Zero< %s >();' % r
	if cls == 'gen' and m.name == 'Destroy':
		return []  # the host owns the object
	if cls == 'query':
		return [] if r == 'void' else ['\treturn (%s)(%s);' % (r, value if value else '0')]
	lines = []
	if cls != 'sink':
		lines.append('\tlekmod_portable::LogStubOnce("%s::%s");' % (family, m.name))
	if zero:
		lines.append(zero)
	return lines


def main():
	csv_path = os.path.join(REPO, 'headless', 'host', 'api', 'engine-api.csv')
	outdir = os.path.join(REPO, 'headless', 'portable', 'host', 'gen')
	rows = g.read_csv(csv_path)
	os.makedirs(outdir, exist_ok=True)
	for famdef in g.FAMILIES:
		name, headers, derived, chain = famdef
		methods = g.load_family(REPO, famdef)
		cname = 'Portable%sGen' % derived[3:]
		h = [HDR, '#pragma once', '', '#include "lekmod_portable/engine_ifaces.h"', '',
		     'class %s : public %s' % (cname, derived), '{', 'public:']
		cpp = [HDR, '#include "CvGameCoreDLLPCH.h"', '#include "%s.h"' % cname, '#include "lekmod_portable/host_log.h"', '']
		for m in methods:
			r = rows.get((name, m.name))
			cls, value = (r['class'], r['value']) if r else ('sim', '')
			h.append('\tvirtual %s;' % m.sig())
			if m.name == 'QueryInterface' and m.iface == 'ICvUnknown':
				guids = ['guid%s' % c for c in chain]
				cpp.append('%s\n{' % m.sig(cname + '::'))
				cpp.append('\tif(%s)' % ' ||\n\t\t'.join('%s == %s' % (m.params[0][1], gd) for gd in guids))
				cpp.append('\t\treturn this;')
				cpp.append('\treturn NULL;')
				cpp.append('}')
				continue
			b = body(m, name, cls, value)
			cpp.append('%s\n{\n%s\n}' % (m.sig(cname + '::'), '\n'.join(b)))
		h.append('};')
		for fn, content in ((cname + '.h', '\n'.join(h) + '\n'), (cname + '.cpp', '\n'.join(cpp) + '\n')):
			p = os.path.join(outdir, fn)
			with open(p, 'w', newline='\n') as f:
				f.write(content)
		print('%s: %d methods' % (cname, len(methods)))
	return 0


if __name__ == '__main__':
	sys.exit(main())
