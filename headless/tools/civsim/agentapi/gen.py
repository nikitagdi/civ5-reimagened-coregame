class GenError(Exception):
    pass


def snake(p: str) -> str:
    p = re.sub(r"^(sz|[a-z])(?=[A-Z])", "", p)
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", p).lower()


def api_type(ctype: str, pname: str) -> str:
    t = re.sub(r"\b(const|unsigned)\b|[&*]", "", ctype).strip()
    if t == "plot":
        return "plot"
    if pname == "iUnitID":
        return "unit_ref"
    if pname in ("iCityID", "iCity", "iCity1", "iCity2"):
        return "city_ref"
    if t == "bool":
        return "bool"
    if t in ("int", "short", "uint", "long"):
        return "int"
    if t in ("CvString", "char") or "char" in ctype:
        return "string"
    if t == "PlayerTypes":
        return "player"
    if t == "TeamTypes":
        return "team"
    if t == "LeagueTypes":
        return "league_id"
    if t in ENUMS:
        return "enum:" + ENUMS[t]
    return "opaque:" + t


def collapse_xy(params: list[tuple[str, str]]) -> list[tuple[str, str]]:
    out: list[tuple[str, str]] = []
    i = 0
    while i < len(params):
        t, n = params[i]
        nxt = params[i + 1] if i + 1 < len(params) else None
        if nxt and any(n == x and nxt[1] == y for x, y in XY):
            out.append(("plot", f"{n},{nxt[1]}"))
            i += 2
        else:
            out.append((t, n))
            i += 1
    return out


def longest(decls: list[dllparse.Decl], name: str) -> dllparse.Decl | None:
    c = [d for d in decls if d.name == name]
    return max(c, key=lambda d: len(d.params)) if c else None


class Ctx:
    def __init__(self, dll_src: Path, fixes: list[dict]):
        self.sends = dllparse.parse_sends(dll_src)
        self.resps = dllparse.parse_responses(dll_src)
        self.hline = dllparse.handler_lines(dll_src)
        self.sline = dllparse.sync_lines(self.sends)
        self.fixes = {r["id"]: r for r in fixes if r.get("kind") == "validation"}


def _as_list(x: object) -> list[str]:
    return [] if not x else ([x] if isinstance(x, str) else list(x))


def build_args(spec: dict, ctx: Ctx) -> tuple[list[dict], str | None]:
    sends = _as_list(spec.get("send"))
    resp = longest(ctx.resps, spec["resp"]) if spec.get("resp") else None
    snd = longest(ctx.sends, sends[0]) if sends else None
    src = resp or snd
    if spec["cls"] in ("server", "pregame", "unsupported") or src is None:
        return list(spec.get("args", [])), None
    params = collapse_xy(list(src.params))
    actor = spec.get("actor")
    if actor is None and resp and params and params[0][0] == "PlayerTypes" and params[0][1].startswith("e"):
        actor = params[0][1]
    drop = set(spec.get("drop", []))
    over = spec.get("over", {})
    args: list[dict] = []
    for ctype, pname in params:
        if pname == actor or pname in drop:
            continue
        t = api_type(ctype, pname)
        a: dict = {"name": "plot" if "," in pname else RENAMES.get(pname) or snake(pname), "type": t, "wire_name": pname}
        if t in ("unit_ref", "city_ref"):
            a["own"] = True
        if t == "string":
            a["max_len"] = 127
        a.update(over.get(pname, {}))
        if a["type"].startswith("opaque:"):
            raise GenError(f"{spec['name']}: argument {pname} has unmapped type {a['type']} (add drop/derived or over)")
        args.append(a)
    args += spec.get("extra_args", [])
    return args, actor


def phase_of(spec: dict) -> list[str]:
    if "phase" in spec:
        return spec["phase"]
    return ["turn_active"] if spec["cls"] in schema.CLIENT_CLASSES else []


def auto_rules(spec: dict, args: list[dict], actor: str | None, phase: list[str], rate: str, hand: list[str]) -> list[str]:
    cls = spec["cls"]
    have = {r.split("/", 1)[0] for r in hand}
    if cls in schema.FORBIDDEN_CLASSES:
        return [f"class/auto: rejected 'forbidden' before any other check (class {cls})"] + hand
    if cls == "helper":
        return ["class/auto: client/SDK-side helper, never sent as is; every expanded command is validated on its own"]
    r = [f"class/auto: client command (class {cls})",
         "range/auto: arguments decode per the args schema (types, enums by Type string, string max_len, UTF-8, no control characters)"]
    if actor:
        r.append(f"player/auto: acting player is session.player (wire {actor} is filled from the session, never from the payload)")
    for a in args:
        n, t = a["name"], a["type"]
        if t == "player" and "player" not in have:
            kind = {"major": "[0, MAX_MAJOR_CIVS)", "minor": "[MAX_MAJOR_CIVS, MAX_CIV_PLAYERS)"}.get(a.get("pkind"), "[0, MAX_PLAYERS)")
            r.append(f"player/auto: {n} is a player id in {kind} and alive")
        elif t == "team" and "player" not in have:
            r.append(f"player/auto: {n} is a team id in [0, MAX_TEAMS)")
        elif t == "plot" and "range" not in have:
            r.append(f"range/auto: {n} inside map bounds" + (" or (-1,-1)" if a.get("none") else ""))
        if ("min" in a or "max" in a) and "range" not in have:
            r.append(f"range/auto: {n} in [{a.get('min', '-inf')}, {a.get('max', 'inf')}]")
        if "reserved_below" in a or "reserved_above" in a:
            r.append(f"range/auto: {n} outside the reserved multiplexer range is required, else reserved_value")
    if "ownership" not in have:
        own = [a["name"] for a in args if a.get("own")]
        r.append("ownership/auto: " + (f"{', '.join(own)} exists and owner == session.player" if own
                                       else "not required: the command references no unit or city"))
    for p in phase:
        if p == "turn_active":
            r.append("phase/auto: the session player's turn is active, the game is not paused, loading or resyncing")
        elif p == "any":
            r.append("phase/auto: any phase (no turn-state requirement), session connected")
        else:
            r.append(f"pending/auto: decision {p.split(':', 1)[1]} is pending for session.player (observation 'pending')")
    r.append(f"rate/auto: rate class '{rate}'")
    if "applicability" not in have:
        r.append("applicability/auto: no can* mapped yet; the handler's own checks only")
    return r + hand


def build_command(spec: dict, ctx: Ctx) -> dict:
    name, cls = spec["name"], spec["cls"]
    args, actor = build_args(spec, ctx)
    phase = phase_of(spec)
    rate = "none" if cls not in schema.CLIENT_CLASSES else spec.get("rate", "turn" if cls == "turn" else "player")
    hand = [f"applicability/hand: {t}" for t in _as_list(spec.get("app"))] + list(spec.get("rules", []))
    gaps = []
    for gid in spec.get("gaps", []):
        g = {"id": gid, "fix": None, "flag": None, "dll_status": "none", "gap": overlay.GAPS[gid], "dll_scope": None,
             "dll_note": "found by the V1 audit of the other handlers; host validator only, candidate for a FIX-VALIDATION record"}
        if gid.startswith("FIX-"):
            rec = ctx.fixes.get(gid)
            if rec is None:
                raise GenError(f"{name}: {gid} is not a validation record in fixes.json")
            note = rec["notes"] if rec["status"] != "not-implemented" else f"{rec['after']} {rec['notes']}"
            g.update(fix=gid, flag=rec["flag"], dll_status=rec["status"], dll_scope=rec["scope"], dll_note=note)
        gaps.append(g)
    sends, resps = _as_list(spec.get("send")), _as_list(spec.get("resp"))
    ifaces: list[str] = []
    srcs: list[str] = []
    for s in sends:
        d = longest(ctx.sends, s)
        if d is None:
            raise GenError(f"{name}: send* '{s}' not found in ICvDLLUtility.h")
        ifaces.append(d.iface)
        srcs.append(ctx.sline[s])
    for r_ in resps:
        d = longest(ctx.resps, r_)
        if d is None:
            raise GenError(f"{name}: Response* '{r_}' not found in the handler interfaces")
        ifaces.append(d.iface)
        srcs.append(f"{d.file}:{d.line}; CvDllNetMessageHandler.cpp:{ctx.hline[r_]}")
    lua = [f"Network.{x}" for x in _as_list(spec.get("lua"))]
    one = lambda xs: None if not xs else xs[0] if len(xs) == 1 else xs
    wire = {"send": one(sends), "response": one(resps), "lua": one(lua), "iface": "/".join(dict.fromkeys(ifaces)) or None,
            "net_msg": None, "src": "; ".join(dict.fromkeys(srcs)) or None}
    for k in ("mux", "derived", "exe"):
        if spec.get(k):
            wire[k] = spec[k]
    if actor:
        wire["actor"] = actor
    cmd = {"name": name, "since": "1.0", "class": cls, "wire": wire, "args": args,
           "validate": auto_rules(spec, args, actor, phase, rate, hand), "dll_gaps": gaps,
           "turn_phase": phase, "rate": rate}
    for k, key in (("expands_to", "expands_to"), ("note", "note")):
        if spec.get(k):
            cmd[key] = spec[k]
    if spec.get("tags"):
        cmd["tags"] = list(spec["tags"])
    return cmd


def build_commands(dll_src: Path, fixes: list[dict]) -> dict:
    ctx = Ctx(dll_src, fixes)
    cmds = sorted((build_command(s, ctx) for s in overlay.CMDS), key=lambda c: c["name"])
    return {"schema": 1, "api": API, "dll": DLL_LABEL, "classes": CLASSES, "steps": STEPS, "rates": RATES,
            "reserved_values": RESERVED, "commands": cmds}


def generate(dll_src: Path, api_dir: Path | None = None, fixes_path: Path | None = None) -> list[str]:
    fixes = json.loads((fixes_path or canon.REPO / "headless" / "improvements" / "fixes.json").read_text(encoding="utf-8"))["fixes"]
    docs = {"commands": build_commands(dll_src, fixes),
            "observation": content.observation(dll_src),
            "events": content.events(),
            "errors": content.errors()}
    bad = []
    for name, doc in docs.items():
        e = schema.validate(doc, schema.SCHEMAS[name])
        bad += [f"{name}: {x}" for x in e]
    bad += schema.check_commands(docs["commands"], fixes)
    if bad:
        raise GenError("generated documents are invalid:\n  " + "\n  ".join(bad))
    return [n for n, d in docs.items() if canon.write(n, d, api_dir)]
